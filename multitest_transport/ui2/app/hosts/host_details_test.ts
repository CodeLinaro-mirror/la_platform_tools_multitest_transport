import {DomPortalOutlet} from '@angular/cdk/portal';
import {Location} from '@angular/common';
import {provideHttpClientTesting} from '@angular/common/http/testing';
import {DebugElement, LOCALE_ID} from '@angular/core';
import {ComponentFixture, TestBed} from '@angular/core/testing';
import {MAT_DIALOG_DATA} from '@angular/material/dialog';
import {NoopAnimationsModule} from '@angular/platform-browser/animations';
import {ActivatedRoute, convertToParamMap, Router} from '@angular/router';
import {BehaviorSubject, of as observableOf} from 'rxjs';

import {APP_DATA} from '../services';
import {CommonParamsService} from '../services/common_params_service';
import {FeedbackService} from '../services/feedback_service';
import {SurveyTrigger} from '../services/mtt_lab_models';
import {Notifier} from '../services/notifier';
import {PreferenceService} from '../services/preference_service';
import {TfcClient} from '../services/tfc_client';
import {HeaderSlotService} from '../shared/header_slot_service';
import {EntityType, V6IframeContainerComponent} from '../shared/v6_iframe_container_component';
import {getEl, getEls} from '../testing/jasmine_util';
import {newMockAppData, newMockDeviceInfosResponse, newMockLabHostInfo} from '../testing/mtt_lab_mocks';

import {HostDetails} from './host_details';
import {HostsModule} from './hosts_module';

describe('HostDetails', () => {
  let feedbackService: jasmine.SpyObj<FeedbackService>;
  let hostDetails: HostDetails;
  let hostDetailsFixture: ComponentFixture<HostDetails>;
  let el: DebugElement;
  let routerSpy: jasmine.SpyObj<Router>;
  let tfcClient: jasmine.SpyObj<TfcClient>;
  let notifierSpy: jasmine.SpyObj<Notifier>;
  let containerSpy: jasmine.SpyObj<V6IframeContainerComponent>;
  let preferenceServiceSpy: jasmine.SpyObj<PreferenceService>;
  let useLabConsoleUISubject$: BehaviorSubject<boolean>;
  let commonParams: Record<string, string>;

  const hostname = 'host1';
  const hostInfo = newMockDeviceInfosResponse(hostname);
  const queryParams = {
    hostnameStorageKey: 'mockStorageKey',
  };

  beforeEach(() => {
    commonParams = {};
    feedbackService = jasmine.createSpyObj('feedbackService', ['startSurvey']);
    routerSpy = jasmine.createSpyObj(
        'Router',
        ['navigateByUrl', 'navigate', 'createUrlTree', 'serializeUrl']);
    // TODO: Wait until b/208710526 is fixed, then remove this autogenerated
    // error suppression.
    //  @ts-ignore(go/unfork-jasmine-typings): Argument of type '{}' is not
    //  assignable to parameter of type 'UrlTree'.
    routerSpy.createUrlTree.and.returnValue({});
    routerSpy.serializeUrl.and.returnValue('/hosts/' + hostname);

    tfcClient = jasmine.createSpyObj('tfcClient', {
      getDeviceInfosFromHost: observableOf(hostInfo),
      getHostHistory: observableOf({}),
      getHostInfo: observableOf(newMockLabHostInfo(hostname)),
      getHostNotes: observableOf({}),
      getHostResource: observableOf(null),
      removeHost: observableOf({}),
    });

    notifierSpy = jasmine.createSpyObj('notifier', {
      confirm: observableOf(true),  // mock confirm click in dialog.
      showMessage: observableOf({}),
      showError: observableOf({}),
    });

    containerSpy = jasmine.createSpyObj('V6IframeContainerComponent', [
      'navigateForEntity',
      'initIframeUrl',
    ]);
    useLabConsoleUISubject$ = new BehaviorSubject<boolean>(true);
    preferenceServiceSpy = jasmine.createSpyObj('preferenceService', [], {
      useLabConsoleUISubject$,
    });

    TestBed.configureTestingModule({
      imports: [
        HostsModule,
        NoopAnimationsModule,
      ],
      providers: [
        provideHttpClientTesting(),
        {
          provide: ActivatedRoute,
          useValue: {
            params: observableOf({id: hostname}),
            queryParams: observableOf(queryParams),
            queryParamMap: observableOf(convertToParamMap(queryParams)),
          },
        },
        {
          provide: APP_DATA,
          useValue: Object.assign(newMockAppData(), {enableLabConsoleUI: true}),
        },
        {provide: FeedbackService, useValue: feedbackService},
        {
          provide: CommonParamsService,
          useValue: {getCommonParams: () => commonParams},
        },
        {provide: LOCALE_ID, useValue: 'en-US'},
        {provide: MAT_DIALOG_DATA, useValue: {}},
        {provide: Notifier, useValue: notifierSpy},
        {provide: PreferenceService, useValue: preferenceServiceSpy},
        {provide: Router, useValue: routerSpy},
        {provide: TfcClient, useValue: tfcClient},
        {provide: V6IframeContainerComponent, useValue: containerSpy},
      ],
    });
    hostDetailsFixture = TestBed.createComponent(HostDetails);
    hostDetails = hostDetailsFixture.componentInstance;
    hostDetailsFixture.componentRef.setInput('id', hostname);
    hostDetailsFixture.detectChanges();
    el = hostDetailsFixture.debugElement;
  });

  it('should gets initialized correctly', () => {
    expect(hostDetails).toBeTruthy();
  });

  it('calls window.history.back when the back button clicked', () => {
    const backSpy = spyOn(TestBed.inject(Location), 'back');
    getEl(el, '#back-button').click();
    expect(backSpy).toHaveBeenCalledTimes(1);
  });

  it('should remove host correctly', () => {
    hostDetails.id = hostname;
    hostDetails.removeHost();
    expect(tfcClient.removeHost).toHaveBeenCalledWith(hostname);
  });

  it('should add hostname to dropdown option when no others', () => {
    hostDetails.hostnames = [];
    hostDetails.id = hostname;
    hostDetails.appendDefaultOption();
    expect(hostDetails.hostnames[0]).toEqual(hostname);
  });

  it('should navigate to the selected host when selection change', () => {
    hostDetails.load(hostname, true);
    expect(routerSpy.navigate).toHaveBeenCalledWith(['/hosts/' + hostname], {
      queryParams: {},
      replaceUrl: true
    });
  });

  it('should preserve the common query params when selection change', () => {
    commonParams = {'debug': 'true', 'fake_data': '1'};
    hostDetails.load(hostname, true);
    expect(routerSpy.navigate).toHaveBeenCalledWith(['/hosts/' + hostname], {
      queryParams: {'debug': 'true', 'fake_data': '1'},
      replaceUrl: true,
    });
  });

  it('should call HaTS client on host notes display', async () => {
    getEls(el, '.mdc-tab').find(x => x.textContent === 'Notes')!.click();
    hostDetailsFixture.detectChanges();
    await new Promise(resolve => {
      setTimeout(resolve);
    });
    expect(feedbackService.startSurvey)
        .toHaveBeenCalledWith(SurveyTrigger.HOST_NOTES);
  });

  it('should call HaTS client on host navigation', () => {
    hostDetails.startHostNavigationHats();
    expect(feedbackService.startSurvey)
        .toHaveBeenCalledWith(SurveyTrigger.HOST_NAVIGATION);
  });

  it('should load host correctly when calling refresh method', () => {
    spyOn(hostDetails.hostDetailsSummary, 'loadHost');
    hostDetails.id = hostname;

    hostDetails.refresh();
    expect(tfcClient.getHostInfo).toHaveBeenCalledWith(hostname);
    expect(hostDetails.hostDetailsSummary.loadHost)
        .toHaveBeenCalledWith(hostname);
  });

  it('should call initIframeUrl on init if Lab Console UI is enabled', () => {
    expect(containerSpy.initIframeUrl)
        .toHaveBeenCalledWith(EntityType.HOSTS, hostname);
  });

  it('should call navigateForEntity when id changes', () => {
    const newId = 'host2';
    hostDetailsFixture.componentRef.setInput('id', 'temp');
    hostDetailsFixture.detectChanges();
    hostDetailsFixture.componentRef.setInput('id', newId);
    hostDetailsFixture.detectChanges();
    expect(containerSpy.navigateForEntity)
        .toHaveBeenCalledWith(EntityType.HOSTS, newId);
  });

  describe('header slot', () => {
    let headerSlotService: HeaderSlotService;

    beforeEach(() => {
      headerSlotService = TestBed.inject(HeaderSlotService);
    });

    afterEach(() => {
      headerSlotService.setSlotElement(null);
    });

    it('keeps the page header when the app header has no slot', () => {
      expect(hostDetails.isHeaderInAppHeaderSlot).toBeFalse();
      expect(getEl(el, '.header')).toBeTruthy();
      expect(headerSlotService.portal$.value).toBeNull();
    });

    it('moves the page header into the app header slot in Lab Console mode', () => {
      headerSlotService.setSlotElement(document.createElement('div'));
      const fixture = TestBed.createComponent(HostDetails);
      fixture.componentRef.setInput('id', hostname);
      fixture.detectChanges();

      expect(fixture.componentInstance.isHeaderInAppHeaderSlot).toBeTrue();
      expect(fixture.nativeElement.querySelector('.header')).toBeNull();
      const portal = headerSlotService.portal$.value;
      expect(portal).not.toBeNull();

      // The slot content offers the back button, the "Hosts" breadcrumb and
      // the host switcher.
      const host = document.createElement('div');
      document.body.appendChild(host);
      const outlet = new DomPortalOutlet(host);
      outlet.attach(portal!);
      fixture.detectChanges();
      expect(host.querySelector('#back-button')).toBeTruthy();
      expect(host.querySelector('.header-crumb')!.textContent).toContain('Hosts');
      expect(host.querySelector('mat-select.entity-switcher')).toBeTruthy();
      outlet.dispose();
      host.remove();

      // Switching back to the legacy UI restores the page header.
      useLabConsoleUISubject$.next(false);
      fixture.detectChanges();
      expect(fixture.componentInstance.isHeaderInAppHeaderSlot).toBeFalse();
      expect(fixture.nativeElement.querySelector('.header')).toBeTruthy();
      expect(headerSlotService.portal$.value).toBeNull();
      fixture.destroy();
    });

    it('never uses the app header slot in the dialog (modal) mode', () => {
      headerSlotService.setSlotElement(document.createElement('div'));
      const fixture = TestBed.createComponent(HostDetails);
      // Opened from a dialog: MAT_DIALOG_DATA carries the host name.
      (fixture.componentInstance as {params: HostDetails['params']}).params =
          {id: hostname, newWindow: false};
      fixture.detectChanges();

      expect(fixture.componentInstance.isModalMode).toBeTrue();
      expect(fixture.componentInstance.isHeaderInAppHeaderSlot).toBeFalse();
      expect(fixture.nativeElement.querySelector('.header')).toBeTruthy();
      expect(headerSlotService.portal$.value).toBeNull();
      fixture.destroy();
    });
  });
});
